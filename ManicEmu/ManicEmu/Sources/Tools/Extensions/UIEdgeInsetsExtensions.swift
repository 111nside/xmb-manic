extension UIEdgeInsets {
    static func insets(top: CGFloat = 0, left: CGFloat = 0, bottom: CGFloat = 0, right: CGFloat = 0) -> Self {
        UIEdgeInsets(top: top, left: left, bottom: bottom, right: right)
    }
}
